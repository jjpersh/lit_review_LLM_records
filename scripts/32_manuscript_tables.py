#!/usr/bin/env python3
"""Manuscript-ready tables (Tables 5-7, Supplementary Tables S1-S5) from extraction/extraction.csv and scripts/synth_maps.py.
Run from lit_review_LLM/. Output: synthesis/manuscript_tables.md, with [@Key] citations taken from draft/_work/citation_map.tsv
(rec_ids missing from the map get a placeholder key REC_<rec_id> that must be added to the citation map).
Revision run 2026-11-12. Nothing in this file is typed by hand into the manuscript tables: copy the output."""
import collections
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from synth_maps import S, THEMES, T5, TIM, DUP  # noqa: E402

rows = list(csv.DictReader(open('extraction/extraction.csv', encoding='utf-8', newline='')))
scr = {r['rec_id']: r for r in csv.DictReader(open('focused_review/screening.csv', encoding='utf-8', newline=''))}
keymap = {}
for line in open('draft/_work/citation_map.tsv', encoding='utf-8'):
    parts = line.rstrip('\n').split('\t')
    if len(parts) >= 3:
        rid = parts[2].split(' ')[0]
        keymap[rid] = parts[1]
extra = 'draft/_work/citation_map_extra.tsv'   # rec_id <tab> key, for papers cited only from the revision on
if os.path.exists(extra):
    for line in open(extra, encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) == 2 and not p[0].startswith('#'):
            keymap[p[0]] = p[1]

k = collections.Counter()
for r in rows:
    k[r['rec_id']] += 1
    r['key'] = f"{r['rec_id']}.{k[r['rec_id']]}"
    r.update({f'm_{a}': b for a, b in S[r['key']].items()})
    s = scr[r['rec_id']]
    r['theme'] = THEMES[s['theme']] if s['theme'] in THEMES else s['theme']
    r['process'] = r['adjacent'].strip().lower() == 'no'
    au = s['first_author'].split(' ')[-1]
    r['study'] = f"{au} et al." if True else au
    r['cite'] = f"[@{keymap.get(r['rec_id'], 'REC_' + r['rec_id'])}]"
rows = [r for r in rows if r['key'] not in DUP]  # same experiment as another setup: counted once (2026-11-13)

# study names as printed in the first draft (surname of first author; 'and' for two authors)
NAMES = {'S002': 'Shou et al.', 'S004': 'Luna Rueda et al.', 'S007': 'Narimani and Emami', 'S013': 'Tohma et al.',
         'S016': 'Nozari and Yordanova', 'S017': 'Nogueira and Skogestad', 'S020': 'Papacharalampopoulos et al.',
         'S022': 'Vyas et al.', 'S028': 'Hidalgo-Castelo et al.', 'S030': 'Schall', 'S032': 'Rosenthal',
         'S037': 'Vyas and Mercangöz (continuous power)', 'S038': 'Vyas and Mercangöz (on/off)', 'S041': 'Zhang et al.',
         'S042': 'Rasheed et al.', 'S048': 'Rojas-Ordoñez et al.', 'S156': 'González-Potes et al.',
         'S178': 'Ibáñez-Espinel et al.', 'S180': 'Lima et al.', 'S193': 'Chen et al.', 'S195': 'Shu et al.',
         'S203': 'Wen and Sajid', 'S262': 'Pershing et al.', 'S272': 'Miyaoka and Inoue', 'S282': 'Hofmann et al.',
         'S315': 'Nerantzis et al.', 'T0532': 'Wu et al.', 'T0665': 'Naagarajan and Streif', 'T0779': 'Krishna et al.',
         'T1042': 'Arif and Rahim', 'T1046': 'Khan et al.', 'T1053': 'Šmídl and Peroutka',
         # Stage B papers (2026-11-13)
         'S019': 'Wang et al.', 'S026': 'He et al.', 'S031': 'Song et al.', 'S033': 'Wen et al.', 'S036': 'Li et al.',
         'S039': 'Xia et al.', 'S043': 'Gill et al.', 'S205': 'Caracciolo and Vyskočil', 'S239': 'Xue and He',
         'S264': 'Vieira da Silva et al.', 'S269': 'Christofides et al.', 'S302': 'Kasai and Yoshimura',
         'T0608': 'Naagarajan et al.', 'T0615': 'Raghavan and Giridhar', 'T1044': 'Caccia et al.'}
for r in rows:
    r['study'] = NAMES.get(r['rec_id'], r['study'])

AUTH = ['Advise', 'Propose', 'Set targets', 'Act']
EVID = ['E0', 'E1', 'E2', 'E3', 'E4', 'E5']
OUTC = ['Succeeded', 'Conditional', 'Failed', 'Not shown']
CLASS = {'nonllm': 'Non-LLM better', 'tie': 'Tie', 'mixed': 'Mixed', 'llm': 'LLM better', 'nq': 'Not quantified',
         'gate': 'Not LLM vs non-LLM (gate)'}
proc = [r for r in rows if r['process']]
md = []


def table(header, data):
    md.append('| ' + ' | '.join(header) + ' |')
    md.append('|' + '---|' * len(header))
    for d in data:
        md.append('| ' + ' | '.join(str(x) for x in d) + ' |')
    md.append('')


def pct(sub, f):
    return f"{100 * sum(r[f] == 'Y' for r in sub) / len(sub):.0f}%" if sub else '-'


npap = len({r['rec_id'] for r in rows})
md += ['# Manuscript tables (generated by scripts/32_manuscript_tables.py)', '',
       f'{len(rows)} setups from {npap} papers; process systems only: {len(proc)} setups from '
       f'{len({r["rec_id"] for r in proc})} papers.', '']

# ---- Table 5 --------------------------------------------------------------------------------------
c1 = [r for r in rows if r['C1'] == 'Y']
order = ['nonllm', 'tie', 'mixed', 'llm', 'nq', 'gate']
c1.sort(key=lambda r: (r['study'], r['key']))   # setups of one paper stay together ('Same, ...' rows follow their first row)
direct = [r for r in c1 if r['m_h2h'] != 'gate']
# Third draft (2026-11-13): the per-setup head-to-head table is kept here for the record ('Table 5 (per setup)'),
# and the manuscript uses Table S6, one row per paper with coded cells, in the Supplementary material.
md += [f'## Table R5 (per setup, record only: {len(c1)} setups with C1 = Y from {len({r["rec_id"] for r in c1})} papers; '
       f'{len(direct)} direct LLM-vs-non-LLM comparisons from {len({r["rec_id"] for r in direct})} papers)', '']
table(['Study', 'Setup', 'Non-LLM comparator', 'Result', 'Class'],
      [[f"{r['study']} {r['cite']}" + ('' if r['evidence'] == 'E1' else f" ({r['evidence']})"),
        T5[r['key']][0], T5[r['key']][1], T5[r['key']][2], CLASS[r['m_h2h']]] for r in c1])
CODE = {'nonllm': 'N', 'tie': 'T', 'mixed': 'M', 'llm': 'L', 'nq': 'Q'}
bypaper = collections.OrderedDict()
for r in sorted(direct, key=lambda r: (not r['process'], r['study'])):
    bypaper.setdefault(r['rec_id'], []).append(r)
md += [f'## Table S6. Head-to-head comparisons by paper ({len(direct)} direct comparisons from {len(bypaper)} papers)', '']
s6 = []
