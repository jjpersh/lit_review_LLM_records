import re  # noqa: E402


def trim(s, n=24):
    w = s.replace('|', '/').split()
    return ' '.join(w[:n]) + (' …' if len(w) > n else '')


def part10(rid):
    p = f'focused_review/fullread2/{rid}.md'
    if not os.path.exists(p):
        return None
    m = re.search(r'\n## 10[^\n]*\n(.*?)(\n## |\nSTATUS)', open(p, encoding='utf-8').read(), re.S)
    if not m:
        return None
    line = [x for x in m.group(1).strip().splitlines() if x.strip().startswith(rid)]
    cells = [c.strip().strip('`') for c in line[0].split('|')] if line else []
    return cells[1:6] if len(cells) >= 6 else None


